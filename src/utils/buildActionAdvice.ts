export function buildActionAdvice(input: ActionInput): string[] {
  const { questionType, tendency } = input;

  const templates = TEMPLATE_MAP[questionType];
  if (templates && templates[tendency]) {
    return templates[tendency];
  }

  const fallback = ACTION_DECISION[tendency];
  if (fallback) return fallback;

  return [
    "冷静下来再看一看",
    "不要急着做决定",
    "先理清自己真正关心什么",
  ];
}
