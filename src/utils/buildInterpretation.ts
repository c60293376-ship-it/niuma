const HEXAGRAM_HINTS: Record<string, string> = {
  减损: "损卦讲减损取舍——有所取舍、精简投入",
  损益: "损益之间要有分寸——有所为有所不为",
  节制: "节卦讲节制分寸——设定边界、控制范围",
  增益: "益卦讲增益——适合投入，但要有重点",
  屯难: "屯卦讲起始之难——先打通第一步",
  蹇难: "蹇卦讲阻滞——当前路径有阻，需换一条路",
  困境: "困卦讲资源受限——不能硬耗，找最优解",
};

function enrichWithHexagram(base: string, keywords: string[]): string {
  const hints: string[] = [];
  for (const kw of keywords) {
    for (const [key, hint] of Object.entries(HEXAGRAM_HINTS)) {
      if (kw.includes(key) || key.includes(kw)) {
        if (!hints.includes(hint)) hints.push(hint);
      }
    }
  }
  if (hints.length === 0) return base;
  return base + " " + hints.join("；") + "。";
}
