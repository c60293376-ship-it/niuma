export function buildInterpretation(input: InterpretationInput): string {
  const { questionType, tendency, hexagramKeywords } = input;

  // 查模板
  const templates = TEMPLATE_MAP[questionType];
  if (templates && templates[tendency]) {
    return enrichWithHexagram(templates[tendency], hexagramKeywords);
  }

  // 回退到 action_decision 模板
  const fallback = ACTION_DECISION[tendency];
  if (fallback) {
    return enrichWithHexagram(fallback, hexagramKeywords);
  }

  // 最终回退
  return "保持平常心，静观其变。先理清自己真正关心什么，再决定下一步怎么走。";
}

